type QuestionMetadata = {
    sourceDocument: 'syllabus' | 'exam-regulations'
    sourceSection: string
    learningObjective?: LearningObjectiveId
    cognitiveLevel: 'K1' | 'K2'
}

function createQuestionMetadata(): Record<string, QuestionMetadata> {
    const metadata: Record<string, QuestionMetadata> = {}
    const addMetadata = (questionId: string, value: QuestionMetadata) => {
        if (metadata[questionId]) throw new Error(`Doppelte Fragenzuordnung: ${questionId}`)
        metadata[questionId] = value
    }

    for (const learningObjective of syllabusObjectives) {
        questionIdsByLearningObjective[learningObjective.id].forEach((questionId) => {
            addMetadata(questionId, {
                sourceDocument: 'syllabus',
                sourceSection: learningObjective.sourceSection,
                learningObjective: learningObjective.id,
                cognitiveLevel: learningObjective.cognitiveLevel,
            })
        })
    }

    examinationRegulationQuestionIds.forEach((questionId) => {
        addMetadata(questionId, {
            sourceDocument: 'exam-regulations',
            sourceSection: 'Kapitel 1-2',
            cognitiveLevel: 'K1',
        })
    })
    syllabusIntroductionQuestionIds.forEach((questionId) => {
        addMetadata(questionId, {
            sourceDocument: 'syllabus',
            sourceSection: 'Lernziele/Kognitive Stufen des Wissens',
            cognitiveLevel: 'K1',
        })
    })

    return metadata
}

